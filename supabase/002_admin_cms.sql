-- ---------- 4) รายงานประกาศ ----------
create table if not exists public.reports (
  id          bigint generated by default as identity primary key,
  product_id  bigint not null references public.products (id) on delete cascade,
  user_id     uuid references public.profiles (id) on delete set null,
  reason      text not null check (char_length(reason) between 1 and 100),
  detail      text not null default '' check (char_length(detail) <= 500),
  status      text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
  created_at  timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid references public.profiles (id) on delete set null
);
create index if not exists reports_product_idx on public.reports (product_id);
-- คนเดียวรายงานประกาศเดิมซ้ำไม่ได้ ระหว่างที่เรื่องยังเปิดอยู่
create unique index if not exists reports_open_once on public.reports (product_id, user_id) where status = 'open';

alter table public.reports enable row level security;

do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'reports'
                 and policyname = 'reports: admin reads') then
    create policy "reports: admin reads" on public.reports for select to authenticated using (public.is_admin());
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'reports'
                 and policyname = 'reports: admin updates') then
    create policy "reports: admin updates" on public.reports
      for update to authenticated using (public.is_admin()) with check (public.is_admin());
  end if;
end $$;
-- การส่งรายงานทำผ่าน sl_report() เท่านั้น จึงไม่เปิด policy insert ตรง

create or replace function public.sl_report(p_id bigint, p_reason text, p_detail text default '')
returns void language plpgsql security definer set search_path = public as $$
declare owner uuid;
begin
  if not public.is_active_user() then raise exception 'กรุณาเข้าสู่ระบบก่อน'; end if;
  select user_id into owner from products where id = p_id;
  if not found then raise exception 'ไม่พบสินค้านี้'; end if;
  if owner = auth.uid() then raise exception 'รายงานประกาศของตัวเองไม่ได้'; end if;
  if char_length(trim(coalesce(p_reason, ''))) = 0 then raise exception 'กรุณาเลือกเหตุผล'; end if;
  insert into reports (product_id, user_id, reason, detail)
  values (p_id, auth.uid(), left(trim(p_reason), 100), left(trim(coalesce(p_detail, '')), 500))
  on conflict (product_id, user_id) where status = 'open' do nothing;
  if not found then raise exception 'คุณรายงานประกาศนี้ไปแล้ว ผู้ดูแลระบบกำลังตรวจสอบ'; end if;
end $$;

create or replace function public.admin_reports()
returns setof jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform public.admin_check();
  return query
    select jsonb_build_object(
      'id', r.id, 'productId', r.product_id, 'productTitle', p.title, 'productImg', p.img,
      'reason', r.reason, 'detail', r.detail, 'status', r.status,
      'reporterName', coalesce(u.name, 'ผู้ใช้ที่ถูกลบ'), 'reporterStudentId', u.student_id,
      'createdAt', public.ms(r.created_at))
    from reports r
    join products p on p.id = r.product_id
    left join profiles u on u.id = r.user_id
    order by (r.status = 'open') desc, r.created_at desc;
end $$;

create or replace function public.admin_set_report(p_id bigint, p_status text)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.admin_check();
  if p_status not in ('open', 'resolved', 'dismissed') then raise exception 'สถานะไม่ถูกต้อง'; end if;
  update reports
  set status = p_status,
      resolved_at = case when p_status = 'open' then null else now() end,
      resolved_by = case when p_status = 'open' then null else auth.uid() end
  where id = p_id;
  if not found then raise exception 'ไม่พบรายงานนี้'; end if;
exception when unique_violation then
  raise exception 'ผู้ใช้คนนี้มีรายงานที่เปิดอยู่สำหรับประกาศนี้แล้ว';
end $$;

