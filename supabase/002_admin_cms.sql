-- ---------- 1) รูปหลายรูปต่อประกาศ ----------
alter table public.products add column if not exists images jsonb not null default '[]'::jsonb;

-- ประกาศเดิมใช้รูปเดียวในคอลัมน์ img → คัดลอกเป็นรูปแรกของ images
update public.products set images = jsonb_build_array(img)
where jsonb_typeof(images) = 'array' and jsonb_array_length(images) = 0 and img is not null;

-- img = รูปหลัก (รูปแรกของ images) เสมอ ใช้ได้ทั้งหน้าเว็บเก่าและใหม่
create or replace function public.products_sync_images()
returns trigger language plpgsql as $$
begin
  if new.images is null or jsonb_typeof(new.images) <> 'array' then
    new.images := '[]'::jsonb;
  end if;
  if jsonb_array_length(new.images) > 10 then
    raise exception 'ใส่รูปได้ไม่เกิน 10 รูปต่อประกาศ';
  end if;
  if jsonb_array_length(new.images) = 0 then
    new.images := jsonb_build_array(coalesce(new.img, 'images/cat-' || new.category || '.svg'));
  end if;
  new.img := new.images ->> 0;
  return new;
end $$;

do $$ begin
  if not exists (select 1 from pg_trigger where tgname = 'products_sync_images'
                 and tgrelid = 'public.products'::regclass) then
    create trigger products_sync_images before insert or update on public.products
      for each row execute function public.products_sync_images();
  end if;
end $$;

