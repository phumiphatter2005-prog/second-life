-- ---------- ตาราง ----------
create table if not exists public.chat_rooms (
  id              bigint generated by default as identity primary key,
  product_id      bigint not null references public.products (id) on delete cascade,
  buyer_id        uuid not null references public.profiles (id) on delete cascade,
  seller_id       uuid not null references public.profiles (id) on delete cascade,
  created_at      timestamptz not null default now(),
  last_message    text not null default '',
  last_message_at timestamptz not null default now(),
  buyer_read_at   timestamptz not null default now(),
  seller_read_at  timestamptz not null default '1970-01-01',
  unique (product_id, buyer_id),
  check (buyer_id <> seller_id)
);
create index if not exists chat_rooms_buyer_idx on public.chat_rooms (buyer_id);
create index if not exists chat_rooms_seller_idx on public.chat_rooms (seller_id);

create table if not exists public.chat_messages (
  id         bigint generated by default as identity primary key,
  room_id    bigint not null references public.chat_rooms (id) on delete cascade,
  sender_id  uuid references public.profiles (id) on delete set null,   -- null = ข้อความจากระบบ
  kind       text not null check (kind in ('text', 'offer', 'swap', 'request', 'meetup', 'contact', 'system', 'passed')),
  body       text not null default '' check (char_length(body) <= 1000),
  data       jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists chat_messages_room_idx on public.chat_messages (room_id, id);
create index if not exists chat_messages_sender_idx on public.chat_messages (sender_id, created_at);

-- บล็อก: ไม่ลบแถว ใช้ active = false แทนการปลดบล็อก
create table if not exists public.chat_blocks (
  blocker_id uuid not null references public.profiles (id) on delete cascade,
  blocked_id uuid not null references public.profiles (id) on delete cascade,
  active     boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id)
);

create table if not exists public.chat_reports (
  id          bigint generated by default as identity primary key,
  room_id     bigint not null references public.chat_rooms (id) on delete cascade,
  reporter_id uuid references public.profiles (id) on delete set null,
  reported_id uuid references public.profiles (id) on delete set null,
  reason      text not null check (char_length(reason) between 1 and 100),
  detail      text not null default '' check (char_length(detail) <= 500),
  status      text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
  created_at  timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid references public.profiles (id) on delete set null
);

-- ---------- Row Level Security: อ่านได้เฉพาะคนในห้องและแอดมิน / เขียนผ่านฟังก์ชันเท่านั้น ----------
alter table public.chat_rooms    enable row level security;
alter table public.chat_messages enable row level security;
alter table public.chat_blocks   enable row level security;
alter table public.chat_reports  enable row level security;

create or replace function public.chat_is_party(p_room bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from chat_rooms r where r.id = p_room and auth.uid() in (r.buyer_id, r.seller_id));
$$;

do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'chat_rooms'
                 and policyname = 'chat_rooms: parties or admin read') then
    create policy "chat_rooms: parties or admin read" on public.chat_rooms for select to authenticated
      using (auth.uid() in (buyer_id, seller_id) or public.is_admin());
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'chat_messages'
                 and policyname = 'chat_messages: parties or admin read') then
    create policy "chat_messages: parties or admin read" on public.chat_messages for select to authenticated
      using (public.chat_is_party(room_id) or public.is_admin());
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'chat_blocks'
                 and policyname = 'chat_blocks: own read') then
    create policy "chat_blocks: own read" on public.chat_blocks for select to authenticated
      using (blocker_id = auth.uid() or public.is_admin());
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'chat_reports'
                 and policyname = 'chat_reports: admin read') then
    create policy "chat_reports: admin read" on public.chat_reports for select to authenticated
      using (public.is_admin());
  end if;
end $$;

-- ---------- ตัวช่วย ----------
create or replace function public.chat_blocked_between(a uuid, b uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from chat_blocks
                 where active and ((blocker_id = a and blocked_id = b) or (blocker_id = b and blocked_id = a)));
$$;

create or replace function public.chat_msg_json(m public.chat_messages)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'id', m.id, 'roomId', m.room_id, 'senderId', m.sender_id,
    'senderName', (select name from profiles where id = m.sender_id),
    'mine', m.sender_id is not null and m.sender_id = auth.uid(),
    'kind', m.kind, 'body', m.body, 'data', m.data, 'createdAt', public.ms(m.created_at));
$$;

/* ข้อความระบบในห้อง (ใช้ภายในฟังก์ชันเท่านั้น) */
create or replace function public.chat_system(p_room bigint, p_body text, p_kind text default 'system', p_sender uuid default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  insert into chat_messages (room_id, sender_id, kind, body) values (p_room, p_sender, p_kind, left(p_body, 1000));
  update chat_rooms set last_message = left(p_body, 120), last_message_at = now() where id = p_room;
end $$;

-- ---------- เปิดห้องแชต (1 ห้องต่อสินค้า 1 ชิ้นต่อผู้สนใจ 1 คน) ----------
create or replace function public.chat_open(p_product bigint)
returns bigint language plpgsql security definer set search_path = public as $$
declare owner uuid; room_id bigint;
begin
  if not public.is_active_user() then raise exception 'กรุณาเข้าสู่ระบบก่อน'; end if;
  select user_id into owner from products where id = p_product;
  if not found then raise exception 'ไม่พบสินค้านี้'; end if;
  if owner is null then raise exception 'ประกาศตัวอย่างนี้ไม่มีผู้ประกาศให้แชต'; end if;
  if owner = auth.uid() then raise exception 'นี่คือประกาศของคุณ'; end if;
  select id into room_id from chat_rooms where product_id = p_product and buyer_id = auth.uid();
  if found then return room_id; end if;
  if public.chat_blocked_between(auth.uid(), owner) then raise exception 'ไม่สามารถเริ่มแชตได้ เนื่องจากมีการบล็อก'; end if;
  insert into chat_rooms (product_id, buyer_id, seller_id) values (p_product, auth.uid(), owner)
  on conflict (product_id, buyer_id) do nothing returning id into room_id;
  if room_id is null then
    select id into room_id from chat_rooms where product_id = p_product and buyer_id = auth.uid();
  end if;
  return room_id;
end $$;

-- ---------- รายการห้อง / จำนวนที่ยังไม่อ่าน ----------
create or replace function public.chat_rooms_list()
returns setof jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'id', r.id, 'productId', p.id, 'productTitle', p.title, 'productImg', p.img,
    'productPrice', p.price, 'productType', p.type, 'productPassed', p.passed,
    'isSeller', r.seller_id = auth.uid(),
    'otherName', coalesce(o.name, 'ผู้ใช้'),
    'lastMessage', r.last_message, 'lastAt', public.ms(r.last_message_at),
    'unread', (select count(*) from chat_messages m where m.room_id = r.id
               and m.sender_id is distinct from auth.uid()
               and m.created_at > case when r.seller_id = auth.uid() then r.seller_read_at else r.buyer_read_at end))
  from chat_rooms r
  join products p on p.id = r.product_id
  left join profiles o on o.id = case when r.seller_id = auth.uid() then r.buyer_id else r.seller_id end
  where auth.uid() in (r.buyer_id, r.seller_id)
    and exists (select 1 from chat_messages m where m.room_id = r.id)
  order by r.last_message_at desc;
$$;

create or replace function public.chat_unread()
returns integer language sql stable security definer set search_path = public as $$
  select count(*)::int from chat_messages m join chat_rooms r on r.id = m.room_id
  where auth.uid() in (r.buyer_id, r.seller_id)
    and m.sender_id is distinct from auth.uid()
    and m.created_at > case when r.seller_id = auth.uid() then r.seller_read_at else r.buyer_read_at end;
$$;

-- ---------- ข้อมูลห้อง + ข้อความ ----------
create or replace function public.chat_room(p_room bigint)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare r chat_rooms; p products; me uuid := auth.uid(); seller boolean;
begin
  select * into r from chat_rooms where id = p_room;
  if not found then raise exception 'ไม่พบห้องแชตนี้'; end if;
  if me is null or (me not in (r.buyer_id, r.seller_id) and not public.is_admin()) then
    raise exception 'คุณไม่ได้อยู่ในห้องแชตนี้';
  end if;
  select * into p from products where id = r.product_id;
  seller := me = r.seller_id;
  return jsonb_build_object(
    'id', r.id, 'productId', p.id, 'productTitle', p.title, 'productImg', p.img, 'productPrice', p.price,
    'productType', p.type, 'productPassed', p.passed, 'productPickup', p.pickup,
    'isSeller', seller, 'isBuyer', me = r.buyer_id, 'adminView', me not in (r.buyer_id, r.seller_id),
    'buyerName', (select name from profiles where id = r.buyer_id),
    'sellerName', (select name from profiles where id = r.seller_id),
    'otherName', (select name from profiles where id = case when seller then r.buyer_id else r.seller_id end),
    'otherReadAt', public.ms(case when seller then r.buyer_read_at else r.seller_read_at end),
    'blockedByMe', exists (select 1 from chat_blocks b where b.active and b.blocker_id = me
                           and b.blocked_id = case when seller then r.buyer_id else r.seller_id end),
    'blocked', public.chat_blocked_between(r.buyer_id, r.seller_id),
    'requesters', case when seller and p.type = 'free' then
      (select count(distinct r2.id) from chat_rooms r2 join chat_messages m on m.room_id = r2.id
       where r2.product_id = p.id and m.kind = 'request') else 0 end);
end $$;

create or replace function public.chat_messages_list(p_room bigint, p_after bigint default 0)
returns setof jsonb language plpgsql stable security definer set search_path = public as $$
begin
  if not (public.chat_is_party(p_room) or public.is_admin()) then raise exception 'คุณไม่ได้อยู่ในห้องแชตนี้'; end if;
  return query
    select public.chat_msg_json(cm) from chat_messages cm
    where cm.id in (select id from chat_messages where room_id = p_room and id > coalesce(p_after, 0)
                    order by id desc limit 500)
    order by cm.id;
end $$;

create or replace function public.chat_mark_read(p_room bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  update chat_rooms set buyer_read_at = now() where id = p_room and buyer_id = auth.uid();
  update chat_rooms set seller_read_at = now() where id = p_room and seller_id = auth.uid();
end $$;

-- ---------- ส่งข้อความ (ตรวจสิทธิ์ ความยาว ส่งรัว บล็อก และกติกาตามประเภทประกาศ) ----------
create or replace function public.chat_send(p_room bigint, p_kind text, p_body text default '', p_data jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r chat_rooms; p products; me uuid := auth.uid(); m chat_messages;
  body text := trim(coalesce(p_body, ''));
  d jsonb := '{}'::jsonb; preview text; amount numeric;
begin
  if not public.is_active_user() then raise exception 'กรุณาเข้าสู่ระบบก่อน'; end if;
  select * into r from chat_rooms where id = p_room;
  if not found then raise exception 'ไม่พบห้องแชตนี้'; end if;
  if me not in (r.buyer_id, r.seller_id) and not public.is_admin() then raise exception 'คุณไม่ได้อยู่ในห้องแชตนี้'; end if;
  if p_kind not in ('text', 'offer', 'swap', 'request', 'meetup', 'contact') then raise exception 'ประเภทข้อความไม่ถูกต้อง'; end if;
  if char_length(body) > 1000 then raise exception 'ข้อความยาวเกิน 1000 ตัวอักษร'; end if;
  if public.chat_blocked_between(r.buyer_id, r.seller_id) then
    raise exception 'ส่งข้อความไม่ได้ เนื่องจากมีการบล็อกในห้องนี้';
  end if;
  -- กันส่งรัว: ไม่เกิน 6 ข้อความใน 10 วินาที
  if (select count(*) from chat_messages where sender_id = me and created_at > now() - interval '10 seconds') >= 6 then
    raise exception 'ส่งข้อความเร็วเกินไป กรุณารอสักครู่';
  end if;
  select * into p from products where id = r.product_id;

  if p_kind = 'text' then
    if body = '' then raise exception 'กรุณาพิมพ์ข้อความ'; end if;
    preview := body;
  elsif p_kind = 'contact' then
    if body = '' then raise exception 'กรุณาใส่ช่องทางติดต่อ'; end if;
    if char_length(body) > 100 then raise exception 'ช่องทางติดต่อยาวเกิน 100 ตัวอักษร'; end if;
    preview := 'ส่งช่องทางติดต่อ';
  elsif p_kind = 'offer' then
    if me <> r.buyer_id then raise exception 'เฉพาะผู้สนใจเท่านั้นที่เสนอราคาได้'; end if;
    if p.type <> 'sell' then raise exception 'เสนอราคาได้เฉพาะประกาศขาย'; end if;
    begin amount := (p_data ->> 'amount')::numeric; exception when others then amount := null; end;
    if amount is null or amount <> round(amount) or amount < 1 or amount > 1000000 then
      raise exception 'กรุณาใส่ราคาเป็นตัวเลข 1–1,000,000 บาท';
    end if;
    d := jsonb_build_object('amount', amount::int, 'status', 'pending');
    preview := 'เสนอราคา ฿' || to_char(amount, 'FM999,999,999');
  elsif p_kind = 'swap' then
    if me <> r.buyer_id then raise exception 'เฉพาะผู้สนใจเท่านั้นที่เสนอของแลกได้'; end if;
    if p.type <> 'swap' then raise exception 'เสนอของแลกได้เฉพาะประกาศแลกเปลี่ยน'; end if;
    if char_length(trim(coalesce(p_data ->> 'title', ''))) not between 1 and 100 then
      raise exception 'กรุณาใส่ชื่อของที่จะนำมาแลก (ไม่เกิน 100 ตัวอักษร)';
    end if;
    d := jsonb_build_object('title', trim(p_data ->> 'title'), 'img', left(coalesce(p_data ->> 'img', ''), 500), 'status', 'pending');
    preview := 'เสนอแลกกับ ' || trim(p_data ->> 'title');
  elsif p_kind = 'request' then
    if me <> r.buyer_id then raise exception 'เฉพาะผู้สนใจเท่านั้นที่ขอรับได้'; end if;
    if p.type <> 'free' then raise exception 'ขอรับได้เฉพาะประกาศแจกฟรี'; end if;
    if p.passed then raise exception 'ของชิ้นนี้ส่งต่อไปแล้ว'; end if;
    if exists (select 1 from chat_messages where room_id = p_room and kind = 'request') then
      raise exception 'คุณขอรับของชิ้นนี้ไปแล้ว';
    end if;
    d := jsonb_build_object('status', 'pending');
    preview := 'ขอรับของชิ้นนี้';
  elsif p_kind = 'meetup' then
    if char_length(trim(coalesce(p_data ->> 'place', ''))) not between 1 and 100 then raise exception 'กรุณาเลือกจุดนัดรับ'; end if;
    if coalesce(p_data ->> 'date', '') !~ '^\d{4}-\d{2}-\d{2}$' or coalesce(p_data ->> 'time', '') !~ '^\d{2}:\d{2}$' then
      raise exception 'กรุณาเลือกวันและเวลานัด';
    end if;
    if (p_data ->> 'date')::date < (now() at time zone 'Asia/Bangkok')::date then raise exception 'วันนัดต้องไม่ใช่วันที่ผ่านมาแล้ว'; end if;
    d := jsonb_build_object('place', trim(p_data ->> 'place'), 'date', p_data ->> 'date', 'time', p_data ->> 'time', 'status', 'pending');
    preview := 'นัดรับ ' || trim(p_data ->> 'place');
  end if;

  insert into chat_messages (room_id, sender_id, kind, body, data) values (p_room, me, p_kind, body, d) returning * into m;
  update chat_rooms set last_message = left(preview, 120), last_message_at = now(),
         buyer_read_at  = case when buyer_id  = me then now() else buyer_read_at end,
         seller_read_at = case when seller_id = me then now() else seller_read_at end
  where id = p_room;
  return public.chat_msg_json(m);
end $$;

-- ---------- ตอบรับ / ปฏิเสธ (ข้อเสนอราคา ของแลก การขอรับ) และยืนยันนัด ----------
create or replace function public.chat_respond(p_message bigint, p_action text)
returns void language plpgsql security definer set search_path = public as $$
declare m chat_messages; r chat_rooms; me uuid := auth.uid(); new_status text; note text;
begin
  if not public.is_active_user() then raise exception 'กรุณาเข้าสู่ระบบก่อน'; end if;
  select * into m from chat_messages where id = p_message;
  if not found then raise exception 'ไม่พบข้อความนี้'; end if;
  select * into r from chat_rooms where id = m.room_id;
  if me not in (r.buyer_id, r.seller_id) then raise exception 'คุณไม่ได้อยู่ในห้องแชตนี้'; end if;
  if public.chat_blocked_between(r.buyer_id, r.seller_id) then raise exception 'ทำรายการไม่ได้ เนื่องจากมีการบล็อกในห้องนี้'; end if;
  if coalesce(m.data ->> 'status', '') <> 'pending' then raise exception 'รายการนี้ตอบไปแล้ว'; end if;

  if m.kind in ('offer', 'swap', 'request') then
    if me <> r.seller_id then raise exception 'เฉพาะผู้ประกาศเท่านั้นที่ตอบรับได้'; end if;
    if p_action not in ('accept', 'reject') then raise exception 'คำสั่งไม่ถูกต้อง'; end if;
    if m.kind = 'request' and p_action = 'accept' then
      perform public.chat_give(r.id);
      return;
    end if;
    new_status := case when p_action = 'accept' then 'accepted' else 'rejected' end;
    note := case m.kind
      when 'offer' then (case when p_action = 'accept' then 'ผู้ประกาศรับข้อเสนอ ฿' else 'ผู้ประกาศปฏิเสธข้อเสนอ ฿' end)
                        || to_char((m.data ->> 'amount')::numeric, 'FM999,999,999')
      when 'swap' then (case when p_action = 'accept' then 'ผู้ประกาศรับข้อเสนอแลกกับ ' else 'ผู้ประกาศปฏิเสธข้อเสนอแลกกับ ' end)
                        || (m.data ->> 'title')
      else 'ผู้ประกาศปฏิเสธคำขอรับ' end;
  elsif m.kind = 'meetup' then
    if me = m.sender_id then raise exception 'อีกฝ่ายเป็นคนยืนยันนัด'; end if;
    if p_action not in ('confirm', 'reject') then raise exception 'คำสั่งไม่ถูกต้อง'; end if;
    new_status := case when p_action = 'confirm' then 'confirmed' else 'rejected' end;
    note := case when p_action = 'confirm' then 'ยืนยันนัดรับแล้ว: ' else 'ไม่สะดวกนัด: ' end
            || (m.data ->> 'place') || ' ' || (m.data ->> 'date') || ' ' || (m.data ->> 'time');
  else
    raise exception 'ข้อความนี้ตอบรับไม่ได้';
  end if;

  update chat_messages set data = jsonb_set(data, '{status}', to_jsonb(new_status)) where id = m.id;
  perform public.chat_system(r.id, note);
end $$;

-- ---------- แจกฟรี: ผู้ประกาศเลือกว่าจะให้ใคร ----------
create or replace function public.chat_give(p_room bigint)
returns void language plpgsql security definer set search_path = public as $$
declare r chat_rooms; p products; other record;
begin
  if not public.is_active_user() then raise exception 'กรุณาเข้าสู่ระบบก่อน'; end if;
  select * into r from chat_rooms where id = p_room;
  if not found then raise exception 'ไม่พบห้องแชตนี้'; end if;
  if auth.uid() <> r.seller_id then raise exception 'เฉพาะผู้ประกาศเท่านั้นที่เลือกผู้รับได้'; end if;
  select * into p from products where id = r.product_id;
  if p.type <> 'free' then raise exception 'เลือกผู้รับได้เฉพาะประกาศแจกฟรี'; end if;
  if not exists (select 1 from chat_messages where room_id = p_room and kind = 'request') then
    raise exception 'ผู้ใช้คนนี้ยังไม่ได้ขอรับ';
  end if;
  if exists (select 1 from chat_messages m join chat_rooms r2 on r2.id = m.room_id
             where r2.product_id = p.id and m.kind = 'request' and m.data ->> 'status' = 'accepted') then
    raise exception 'คุณเลือกผู้รับของชิ้นนี้ไปแล้ว';
  end if;

  update chat_messages set data = jsonb_set(data, '{status}', '"accepted"')
  where room_id = p_room and kind = 'request';
  perform public.chat_system(p_room, 'ผู้ประกาศเลือกให้คุณเป็นผู้รับ นัดรับกันได้เลย');

  for other in
    select distinct r2.id from chat_rooms r2 join chat_messages m on m.room_id = r2.id
    where r2.product_id = p.id and r2.id <> p_room and m.kind = 'request' and m.data ->> 'status' = 'pending'
  loop
    update chat_messages set data = jsonb_set(data, '{status}', '"rejected"')
    where room_id = other.id and kind = 'request';
    perform public.chat_system(other.id, 'ผู้ประกาศมอบของชิ้นนี้ให้ผู้ขอคนอื่นแล้ว ขอบคุณที่สนใจ');
  end loop;
end $$;

create or replace function public.chat_requesters(p_product bigint)
returns setof jsonb language plpgsql stable security definer set search_path = public as $$
begin
  if not exists (select 1 from products where id = p_product and user_id = auth.uid()) then
    raise exception 'เฉพาะผู้ประกาศเท่านั้น';
  end if;
  return query
    select jsonb_build_object('roomId', r.id, 'name', u.name, 'status', m.data ->> 'status',
                              'requestedAt', public.ms(m.created_at))
    from chat_rooms r
    join chat_messages m on m.room_id = r.id and m.kind = 'request'
    join profiles u on u.id = r.buyer_id
    where r.product_id = p_product
    order by m.created_at;
end $$;

-- ---------- ผู้ประกาศกด "ส่งต่อแล้ว" ในห้องแชต → อีกฝ่ายได้การ์ดให้ดาว ----------
create or replace function public.chat_passed(p_room bigint)
returns void language plpgsql security definer set search_path = public as $$
declare r chat_rooms;
begin
  if not public.is_active_user() then raise exception 'กรุณาเข้าสู่ระบบก่อน'; end if;
  select * into r from chat_rooms where id = p_room;
  if not found then raise exception 'ไม่พบห้องแชตนี้'; end if;
  if auth.uid() <> r.seller_id then raise exception 'เฉพาะผู้ประกาศเท่านั้น'; end if;
  if exists (select 1 from chat_messages where room_id = p_room and kind = 'passed') then
    raise exception 'ยืนยันส่งต่อในห้องนี้ไปแล้ว';
  end if;
  update products set passed = true where id = r.product_id;
  perform public.chat_system(p_room, 'ผู้ประกาศยืนยันว่าส่งต่อแล้ว', 'passed', r.seller_id);
end $$;

-- ---------- บล็อก / รายงาน ----------
create or replace function public.chat_block(p_room bigint, p_block boolean)
returns void language plpgsql security definer set search_path = public as $$
declare r chat_rooms; other uuid;
begin
  if not public.is_active_user() then raise exception 'กรุณาเข้าสู่ระบบก่อน'; end if;
  select * into r from chat_rooms where id = p_room;
  if not found or auth.uid() not in (r.buyer_id, r.seller_id) then raise exception 'คุณไม่ได้อยู่ในห้องแชตนี้'; end if;
  other := case when auth.uid() = r.buyer_id then r.seller_id else r.buyer_id end;
  insert into chat_blocks (blocker_id, blocked_id, active) values (auth.uid(), other, p_block)
  on conflict (blocker_id, blocked_id) do update set active = excluded.active, updated_at = now();
end $$;

create or replace function public.chat_report(p_room bigint, p_reason text, p_detail text default '')
returns void language plpgsql security definer set search_path = public as $$
declare r chat_rooms;
begin
  if not public.is_active_user() then raise exception 'กรุณาเข้าสู่ระบบก่อน'; end if;
  select * into r from chat_rooms where id = p_room;
  if not found or auth.uid() not in (r.buyer_id, r.seller_id) then raise exception 'คุณไม่ได้อยู่ในห้องแชตนี้'; end if;
  if char_length(trim(coalesce(p_reason, ''))) = 0 then raise exception 'กรุณาเลือกเหตุผล'; end if;
  if exists (select 1 from chat_reports where room_id = p_room and reporter_id = auth.uid() and status = 'open') then
    raise exception 'คุณรายงานห้องนี้ไปแล้ว ผู้ดูแลระบบกำลังตรวจสอบ';
  end if;
  insert into chat_reports (room_id, reporter_id, reported_id, reason, detail)
  values (p_room, auth.uid(), case when auth.uid() = r.buyer_id then r.seller_id else r.buyer_id end,
          left(trim(p_reason), 100), left(trim(coalesce(p_detail, '')), 500));
end $$;

-- ---------- หลังบ้าน: รายงานแชต ----------
create or replace function public.admin_chat_reports()
returns setof jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform public.admin_check();
  return query
    select jsonb_build_object(
      'id', c.id, 'roomId', c.room_id, 'productTitle', p.title, 'productImg', p.img,
      'reason', c.reason, 'detail', c.detail, 'status', c.status,
      'reporterName', coalesce(a.name, 'ผู้ใช้ที่ถูกลบ'), 'reporterStudentId', a.student_id,
      'reportedName', coalesce(b.name, 'ผู้ใช้ที่ถูกลบ'), 'reportedStudentId', b.student_id,
      'createdAt', public.ms(c.created_at))
    from chat_reports c
    join chat_rooms r on r.id = c.room_id
    join products p on p.id = r.product_id
    left join profiles a on a.id = c.reporter_id
    left join profiles b on b.id = c.reported_id
    order by (c.status = 'open') desc, c.created_at desc;
end $$;

create or replace function public.admin_set_chat_report(p_id bigint, p_status text)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.admin_check();
  if p_status not in ('open', 'resolved', 'dismissed') then raise exception 'สถานะไม่ถูกต้อง'; end if;
  update chat_reports
  set status = p_status,
      resolved_at = case when p_status = 'open' then null else now() end,
      resolved_by = case when p_status = 'open' then null else auth.uid() end
  where id = p_id;
  if not found then raise exception 'ไม่พบรายงานนี้'; end if;
end $$;

-- ภาพรวมหลังบ้าน: เพิ่มจำนวนรายงานแชตที่รอตรวจ (แทนที่ฟังก์ชันจาก 002 ผลลัพธ์เดิมอยู่ครบ)
create or replace function public.admin_overview()
returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform public.admin_check();
  return jsonb_build_object(
    'users',   (select count(*) from profiles),
    'admins',  (select count(*) from profiles where role = 'admin'),
    'banned',  (select count(*) from profiles where banned),
    'items',   (select count(*) from products),
    'passed',  (select count(*) from products where passed),
    'reviews', (select count(*) from reviews),
    'reportsOpen', (select count(*) from reports where status = 'open')
                 + (select count(*) from chat_reports where status = 'open'),
    'chatRooms', (select count(*) from chat_rooms),
    'byCategory', coalesce((select jsonb_object_agg(category, n) from
                    (select category, count(*) n from products group by category) c), '{}'::jsonb),
    'byType',     coalesce((select jsonb_object_agg(type, n) from
                    (select type, count(*) n from products group by type) t), '{}'::jsonb));
end $$;

-- ---------- สินค้า: บอกว่ามีผู้ประกาศให้แชตได้ไหม (แทนที่ฟังก์ชันจาก 002 ผลลัพธ์เดิมอยู่ครบ) ----------
create or replace function public.sl_products(p_id bigint default null, p_owner uuid default null, p_favs boolean default false)
returns setof jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'id', p.id, 'title', p.title, 'price', p.price, 'type', p.type, 'category', p.category,
    'condition', p.condition, 'pickup', p.pickup,
    'contact', case when public.is_active_user() then p.contact end,
    'desc', p.description, 'img', p.img, 'images', p.images, 'passed', p.passed,
    'sellerName', coalesce(u.name, 'Second Life'),
    'hasOwner', p.user_id is not null,
    'isOwner', p.user_id is not null and p.user_id = auth.uid(),
    'isFav', exists (select 1 from favorites f where f.product_id = p.id and f.user_id = auth.uid()),
    'rating', r.avg, 'ratingCount', r.n,
    'sellerRating', s.avg, 'sellerRatingCount', s.n,
    'createdAt', public.ms(p.created_at))
  from products p
  left join profiles u on u.id = p.user_id
  cross join lateral (select avg(stars)::float8 as avg, count(*) as n from reviews where product_id = p.id) r
  cross join lateral (select avg(rv.stars)::float8 as avg, count(*) as n
                      from reviews rv join products p2 on p2.id = rv.product_id
                      where p2.user_id = p.user_id) s
  where (p_id is null or p.id = p_id)
    and (p_owner is null or p.user_id = p_owner)
    and (not p_favs or exists (select 1 from favorites f where f.product_id = p.id and f.user_id = auth.uid()))
  order by case when p_owner is null and not p_favs then p.passed else false end, p.created_at desc;
$$;

