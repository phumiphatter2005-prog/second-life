alter table public.favorites enable row level security;
alter table public.reviews   enable row level security;

-- ทุกการอ่านข้อมูลสาธารณะผ่านฟังก์ชัน sl_* ด้านล่าง (ซ่อนช่องทางติดต่อจากผู้ที่ยังไม่เข้าสู่ระบบ)
drop policy if exists "profiles: read own or admin" on public.profiles;
create policy "profiles: read own or admin" on public.profiles
  for select using (id = auth.uid() or public.is_admin());

drop policy if exists "products: owner or admin reads" on public.products;
create policy "products: owner or admin reads" on public.products
  for select using (user_id = auth.uid() or public.is_admin());

drop policy if exists "products: active users insert own" on public.products;
create policy "products: active users insert own" on public.products
  for insert with check (user_id = auth.uid() and public.is_active_user());

drop policy if exists "products: owner or admin deletes" on public.products;
create policy "products: owner or admin deletes" on public.products
  for delete using ((user_id = auth.uid() and public.is_active_user()) or public.is_admin());

-- favorites / reviews / แก้ไข profile ทำผ่านฟังก์ชันเท่านั้น จึงไม่เปิด policy เขียนตรง

-- ---------- อ่านสินค้า (หน้าแรก / ค้นหา / รายละเอียด / รายการโปรด / ประกาศของฉัน) ----------
create or replace function public.sl_products(p_id bigint default null, p_owner uuid default null, p_favs boolean default false)
returns setof jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'id', p.id, 'title', p.title, 'price', p.price, 'type', p.type, 'category', p.category,
    'condition', p.condition, 'pickup', p.pickup,
    'contact', case when public.is_active_user() then p.contact end,
    'desc', p.description, 'img', p.img, 'passed', p.passed,
    'sellerName', coalesce(u.name, 'Second Life'),
    'isOwner', p.user_id is not null and p.user_id = auth.uid(),
    'isFav', exists (select 1 from favorites f where f.product_id = p.id and f.user_id = auth.uid()),
    'rating', r.avg, 'ratingCount', r.n,
    'sellerRating', s.avg, 'sellerRatingCount', s.n,
    'createdAt', public.ms(p.created_at))
  from products p
  left join profiles u on u.id = p.user_id
  cross join lateral (select avg(stars)::float8 as avg, count(*) as n from reviews where product_id = p.id) r
  cross join lateral (select avg(rv.stars)::float8 as avg, count(*) as n
                      from reviews rv join products p2 on p2.id = rv.product_id
                      where p2.user_id = p.user_id) s
  where (p_id is null or p.id = p_id)
    and (p_owner is null or p.user_id = p_owner)
    and (not p_favs or exists (select 1 from favorites f where f.product_id = p.id and f.user_id = auth.uid()))
  order by case when p_owner is null and not p_favs then p.passed else false end, p.created_at desc;
$$;

create or replace function public.sl_stats()
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'passed', (select count(*) from products where passed),
    'items',  (select count(*) from products),
    'users',  (select count(*) from profiles));
$$;

create or replace function public.sl_reviews(p_id bigint)
returns setof jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('name', u.name, 'stars', r.stars, 'comment', r.comment,
                            'createdAt', public.ms(r.created_at), 'mine', r.user_id = auth.uid())
  from reviews r join profiles u on u.id = r.user_id
  where r.product_id = p_id
  order by r.created_at desc;
$$;

-- ---------- เขียนข้อมูล (ข้อความ error เป็นภาษาไทย แสดงบนหน้าเว็บได้ทันที) ----------
create or replace function public.sl_toggle_fav(p_id bigint)
returns boolean language plpgsql security definer set search_path = public as $$
begin
  if not public.is_active_user() then raise exception 'กรุณาเข้าสู่ระบบก่อน'; end if;
  if not exists (select 1 from products where id = p_id) then raise exception 'ไม่พบสินค้านี้'; end if;
  delete from favorites where user_id = auth.uid() and product_id = p_id;
  if found then return false; end if;
  insert into favorites (user_id, product_id) values (auth.uid(), p_id);
  return true;
end $$;

create or replace function public.sl_toggle_passed(p_id bigint)
returns boolean language plpgsql security definer set search_path = public as $$
declare owner uuid; result boolean;
begin
  if not public.is_active_user() then raise exception 'กรุณาเข้าสู่ระบบก่อน'; end if;
  select user_id into owner from products where id = p_id;
  if not found then raise exception 'ไม่พบสินค้านี้'; end if;
  if owner is distinct from auth.uid() and not public.is_admin() then
    raise exception 'แก้ไขได้เฉพาะประกาศของตัวเอง';
  end if;
  update products set passed = not passed where id = p_id returning passed into result;
  return result;
end $$;

-- ให้ดาวได้คนละ 1 ครั้งต่อสินค้า (ส่งใหม่ = แก้รีวิวเดิม)
create or replace function public.sl_review(p_id bigint, p_stars integer, p_comment text)
returns void language plpgsql security definer set search_path = public as $$
declare owner uuid;
begin
  if not public.is_active_user() then raise exception 'กรุณาเข้าสู่ระบบก่อน'; end if;
  select user_id into owner from products where id = p_id;
  if not found then raise exception 'ไม่พบสินค้านี้'; end if;
  if owner = auth.uid() then raise exception 'ให้ดาวประกาศของตัวเองไม่ได้'; end if;
  if p_stars is null or p_stars not between 1 and 5 then raise exception 'กรุณาเลือกดาว 1–5 ดวง'; end if;
  insert into reviews (product_id, user_id, stars, comment)
  values (p_id, auth.uid(), p_stars, left(trim(coalesce(p_comment, '')), 300))
  on conflict (product_id, user_id) do update
    set stars = excluded.stars, comment = excluded.comment, created_at = now();
end $$;

-- ---------- ระบบหลังบ้าน (เฉพาะผู้ดูแลระบบ) ----------
create or replace function public.admin_check()
returns void language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'เฉพาะผู้ดูแลระบบเท่านั้น'; end if;
end $$;

create or replace function public.admin_overview()
returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform public.admin_check();
  return jsonb_build_object(
    'users',   (select count(*) from profiles),
    'admins',  (select count(*) from profiles where role = 'admin'),
    'banned',  (select count(*) from profiles where banned),
    'items',   (select count(*) from products),
    'passed',  (select count(*) from products where passed),
    'reviews', (select count(*) from reviews),
    'byCategory', coalesce((select jsonb_object_agg(category, n) from
                    (select category, count(*) n from products group by category) c), '{}'::jsonb),
    'byType',     coalesce((select jsonb_object_agg(type, n) from
                    (select type, count(*) n from products group by type) t), '{}'::jsonb));
end $$;

create or replace function public.admin_products()
returns setof jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform public.admin_check();
  return query
    select jsonb_build_object(
      'id', p.id, 'title', p.title, 'price', p.price, 'type', p.type, 'category', p.category,
      'img', p.img, 'passed', p.passed, 'pickup', p.pickup, 'contact', p.contact,
      'sellerName', coalesce(u.name, 'Second Life'), 'sellerStudentId', u.student_id,
      'reviewCount', (select count(*) from reviews r where r.product_id = p.id),
      'createdAt', public.ms(p.created_at))
    from products p left join profiles u on u.id = p.user_id
    order by p.created_at desc;
end $$;

create or replace function public.admin_users()
returns setof jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform public.admin_check();
  return query
    select jsonb_build_object(
      'id', u.id, 'studentId', u.student_id, 'name', u.name, 'role', u.role, 'banned', u.banned,
      'products', (select count(*) from products p where p.user_id = u.id),
      'createdAt', public.ms(u.created_at))
    from profiles u order by u.created_at desc;
end $$;

-- เปลี่ยนสิทธิ์หรือระงับบัญชี (ส่ง null = ไม่เปลี่ยน) แก้บัญชีตัวเองไม่ได้
create or replace function public.admin_set_user(p_id uuid, p_role text default null, p_banned boolean default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.admin_check();
  if p_id = auth.uid() then raise exception 'แก้ไขสิทธิ์บัญชีของตัวเองไม่ได้'; end if;
  if p_role is not null and p_role not in ('user', 'admin') then raise exception 'สิทธิ์ไม่ถูกต้อง'; end if;
  update profiles set role = coalesce(p_role, role), banned = coalesce(p_banned, banned) where id = p_id;
  if not found then raise exception 'ไม่พบผู้ใช้นี้'; end if;
end $$;

create or replace function public.admin_reviews()
returns setof jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform public.admin_check();
  return query
    select jsonb_build_object(
      'productId', r.product_id, 'productTitle', p.title, 'userId', r.user_id, 'name', u.name,
      'stars', r.stars, 'comment', r.comment, 'createdAt', public.ms(r.created_at))
    from reviews r join profiles u on u.id = r.user_id join products p on p.id = r.product_id
    order by r.created_at desc;
end $$;

create or replace function public.admin_delete_review(p_product bigint, p_user uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.admin_check();
  delete from reviews where product_id = p_product and user_id = p_user;
  if not found then raise exception 'ไม่พบรีวิวนี้'; end if;
end $$;

