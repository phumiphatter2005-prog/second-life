-- ---------- ตาราง ----------
create table if not exists public.profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  student_id text unique not null check (student_id ~ '^[0-9]{5,20}$'),
  name       text not null check (char_length(name) between 1 and 60),
  role       text not null default 'user' check (role in ('user', 'admin')),
  banned     boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  user_id     uuid references public.profiles (id) on delete cascade,
  title       text not null check (char_length(title) between 1 and 100),
  price       integer not null default 0 check (price between 0 and 1000000),
  type        text not null check (type in ('sell', 'swap', 'free')),
  category    text not null check (category in ('book', 'clothes', 'stationery', 'electronic', 'dorm', 'other')),
  condition   text not null check (condition in ('ดีมาก', 'ดี', 'พอใช้')),
  pickup      text not null check (char_length(pickup) between 1 and 100),
  contact     text not null check (char_length(contact) between 1 and 100),
  description text not null default 'ไม่มีรายละเอียดเพิ่มเติม' check (char_length(description) <= 1000),
  img         text not null,
  passed      boolean not null default false,
  created_at  timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id    uuid not null references public.profiles (id) on delete cascade,
  product_id bigint not null references public.products (id) on delete cascade,
  primary key (user_id, product_id)
);

create table if not exists public.reviews (
  product_id bigint not null references public.products (id) on delete cascade,
  user_id    uuid not null references public.profiles (id) on delete cascade,
  stars      integer not null check (stars between 1 and 5),
  comment    text not null default '' check (char_length(comment) <= 300),
  created_at timestamptz not null default now(),
  primary key (product_id, user_id)
);

create index if not exists products_user_idx on public.products (user_id);
create index if not exists reviews_user_idx on public.reviews (user_id);

-- ---------- สร้างโปรไฟล์อัตโนมัติเมื่อสมัครสมาชิก ----------
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, student_id, name)
  values (new.id,
          new.raw_user_meta_data ->> 'student_id',
          left(trim(coalesce(new.raw_user_meta_data ->> 'name', '')), 60));
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users for each row execute function public.handle_new_user();

-- ---------- ตัวช่วยตรวจสิทธิ์ ----------
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and role = 'admin' and not banned);
$$;

create or replace function public.is_active_user()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and not banned);
$$;

create or replace function public.ms(t timestamptz)
returns bigint language sql immutable as $$ select (extract(epoch from t) * 1000)::bigint $$;

-- ---------- Row Level Security ----------
alter table public.profiles  enable row level security;
