-- อัปโหลดได้เฉพาะโฟลเดอร์ของตัวเอง: product-images/<user id>/<ไฟล์>
drop policy if exists "product-images: upload own folder" on storage.objects;
create policy "product-images: upload own folder" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'product-images' and (storage.foldername(name))[1] = auth.uid()::text
              and public.is_active_user());

drop policy if exists "product-images: delete own or admin" on storage.objects;
create policy "product-images: delete own or admin" on storage.objects
  for delete to authenticated
  using (bucket_id = 'product-images'
         and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin()));

